    pf.block("p", "ceo", "approve", ref="Q-test", until=T + timedelta(hours=1), actor=ACTOR, now=T)
    assert state() == ("blocked", 0)
    pf.unblock("p", actor=ACTOR, now=T)
    assert pf.get_project("p")["blocker_ref"] is None
    pf.milestone_done("p", 1, "sha1", actor=ACTOR, now=T)
    assert state() == ("working", 50)
    pf.milestone_done("p", 2, "sha2", actor=ACTOR, now=T)
    assert state() == ("done", 100)
    pf.order_close(oid, "shipped", actor=ACTOR, now=T)
    assert state() == ("done", 100)
