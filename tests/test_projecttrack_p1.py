def test_migration_lists_idempotent_and_ddl_matches():
    conn = db.sqlite_connect(":memory:")
    try:
        conn.execute("CREATE TABLE projects (id TEXT PRIMARY KEY)")
        conn.execute("CREATE TABLE milestones (project_id TEXT, n INTEGER)")
        conn.execute("INSERT INTO projects VALUES ('p')")
        db._create_and_migrate(conn, is_pg=False)
        db._create_and_migrate(conn, is_pg=False)
        assert tuple(conn.execute("SELECT kind, beat_n FROM projects").fetchone()) == ("finite", 0)
        ddl = (Path(__file__).resolve().parents[1] / "docs/design/projecttrack-p1-ddl.sql").read_text()
        for table, columns in (("projects", db._PROJECTS_MIGRATION), ("milestones", db._MILESTONES_MIGRATION),
                               ("tasks", [("project_id", "TEXT")])):
            have = {r["name"] for r in conn.execute(f"PRAGMA table_info({table})")}
            for name, kind in columns:
                assert name in have
                assert f"ALTER TABLE {table} ADD COLUMN IF NOT EXISTS {name} {kind};" in ddl
        assert db_pg.PROJECT_EVENT_KIND_CHECK in ddl
        assert "GRANT SELECT, INSERT, UPDATE ON orders TO org_coo;" in ddl
        for statement in db_pg._split_statements(db_pg.PG_SCHEMA):
            assert db._PG_CREATE_RE.match(statement)
    finally:
        conn.close()


