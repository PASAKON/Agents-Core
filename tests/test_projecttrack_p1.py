class Store:
    def __init__(self):
        self.raw = db.sqlite_connect(":memory:")
        self.raw.create_function("btrim", 1, lambda s: s.strip())
        for statement in db_pg._split_statements(db_pg.PG_SCHEMA):
            match = re.match(r"CREATE TABLE IF NOT EXISTS (\w+)", statement)
            if match and match[1] in {"projects", "milestones", "project_events", "orders",
                                     "session_heartbeats", "resource_locks", "ceo_gos"}:
                statement = statement.replace("BIGINT GENERATED BY DEFAULT AS IDENTITY", "INTEGER")
                statement = statement.replace("DEFAULT now()", "DEFAULT CURRENT_TIMESTAMP")
                self.raw.execute(statement)
        db._create_and_migrate(self.raw, is_pg=False)

    def execute(self, sql, params=()):
        sql = sql.replace(" FOR UPDATE", "").replace("::jsonb", "")
        if "SELECT DISTINCT ON (project_id)" in sql:
            sql = ("SELECT project_id, max(at) AS at FROM project_events "
                   "WHERE kind = 'stage' AND body->>'to' = 'parked' GROUP BY project_id")
        return self.raw.execute(sql, tuple(pf.iso(v) if isinstance(v, datetime) else v for v in params))


