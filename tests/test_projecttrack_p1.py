def test_order_lifecycle_and_progress(store):
    project()
    oid = pf.order_take("ship this", "sompong:3", actor=ACTOR, now=T)
    assert re.fullmatch(r"O-20261026-1900-[a-f0-9]{4}", oid)
    def state():
        order = pf._order(store, oid)
        return pf.order_state(order, now=T), pf.order_pct(order, now=T)
    assert state() == ("taken", None)
    pf.order_link(oid, "p", actor=ACTOR, now=T)
    assert state() == ("queued", 0)
    for title in ("one", "two"):
        pf.milestone_add("p", title, actor=ACTOR, order_id=oid, now=T)
    pf.milestone_add("p", "unrelated", actor=ACTOR, now=T)
