@pytest.mark.parametrize("n", [0, 1])
def test_replan_rules(store, days, source, role, allowed, n):
    project(due_at=T, due_set_by=source)
    pf.milestone_add("p", "ship", due_at=T, actor=ACTOR, now=T)
    args = dict(actor=ACTOR, actor_role=role, why="dependency", now=T)
    if not allowed:
        with pytest.raises(PermissionError):
            pf.replan("p", n, T + timedelta(days=days), **args)
        assert store.execute("SELECT count(*) FROM project_events WHERE kind='replan'").fetchone()[0] == 0
        return
    event = pf.replan("p", n, T + timedelta(days=days), **args)
    assert event == {"n": n, "from": pf.iso(T), "to": pf.iso(T + timedelta(days=days)), "why": "dependency"}
    if source == "ceo":
        pf.replan("p", n, T + timedelta(days=5), **args)
        assert pf.get_project("p")["due_first_at"] == (pf.iso(T) if n == 0 else None)


